"""Render the Hadamard research cards and graph reference from dag.json."""

import argparse
from collections import Counter
import json
from urllib.parse import urlsplit

from check_dag import HERE, ancestors, prerequisites, proved, ready_tasks


ROUTE_TITLES = {
    "BANDS": "Capacity-prefix route",
    "CLIQUE-ROUTE": "Pivot clique route",
    "DESIGN-ROUTE": "Full symmetric design route",
    "TAIL-AND-BASE": "Cofinite construction route",
    "NO-DESIGN": "Unrestricted design exclusion",
    "NO-CLIQUES": "Unrestricted pivot pair exclusion",
}


def link(identifier, page=""):
    return f"[{identifier}]({page}#{identifier.lower()})"


def links(identifiers, page=""):
    return ", ".join(link(identifier, page) for identifier in identifiers) or "None"


def source_link(reference):
    url = urlsplit(reference)
    label = url.netloc if url.scheme else reference
    return f"[{label}](<{reference}>)"


def graph_sections(graph, nodes):
    root = graph["root"]
    coverage = set(prerequisites(nodes["YES"])) | {root, "YES", "NO"}
    routes = prerequisites(nodes["ALL-D"]) + prerequisites(nodes["NO"])
    reach = {route: ancestors(route, nodes) | {route} for route in routes}
    counts = Counter(identifier for identifiers in reach.values() for identifier in identifiers)
    shared = {identifier for identifier, count in counts.items() if count > 1} - coverage
    placed = coverage | shared

    yield "Resolution and coverage", coverage
    for route in routes:
        section = reach[route] - placed
        yield ROUTE_TITLES.get(route, route.replace("-", " ").title()), section
        placed.update(section)
    yield "Shared mathematical lemmas", shared
    yield "Supporting mathematics", {identifier for identifier, node in nodes.items()
                                    if identifier not in placed and node["role"] != "diagnostic"}
    yield "Research diagnostics", {identifier for identifier, node in nodes.items()
                                  if identifier not in placed and node["role"] == "diagnostic"}


def dependency_diagram(identifiers, nodes):
    edges = [
        (source, target, arrow)
        for target, node in nodes.items() if target in identifiers
        for field, arrow in (("all_of", "-->"), ("any_of", "-.->"))
        for source in node[field]
    ]
    if not edges:
        return []

    present = {node for source, target, _ in edges for node in (source, target)}
    internal_ids = {identifier: f"N_{i}" for i, identifier in enumerate(nodes) if identifier in present}
    lines = ["~~~mermaid", "flowchart BT"]
    for identifier, internal in internal_ids.items():
        lines.append(f'    {internal}["{identifier}"]')
    for source, target, arrow in edges:
        lines.append(f"    {internal_ids[source]} {arrow} {internal_ids[target]}")
    stubs = [internal for identifier, internal in internal_ids.items() if identifier not in identifiers]
    if stubs:
        lines += ["    classDef external stroke-dasharray:4 3;",
                  f"    class {','.join(stubs)} external;"]
    return lines + ["~~~", ""]


def render_graph(graph, nodes):
    lines = [
        "<!-- Generated by render.py from dag.json. -->",
        "# Closure graph reference",
        "",
        f"Resolution **{graph['resolution']}** · Updated {graph['updated']}",
        "",
        "Every **Required** dependency must be established. When **Alternatives** are listed, "
        "at least one must also be established. The composition explains how these results fit together.",
        "",
        "Diagrams use solid arrows for required dependencies and dotted arrows for alternatives. "
        "Nodes with dashed outlines are defined in another section.",
        "",
        "[Overview](README.md) · [Research tasks](TASKS.md) · [Connecting proofs](lemmas.md)",
        "",
    ]
    sections = [(title, ids) for title, ids in graph_sections(graph, nodes) if ids]
    lines.extend(f"- [{title}](#{title.lower().replace(' ', '-')})" for title, _ in sections)
    lines.append("")
    for heading, identifiers in sections:
        lines += [f"## {heading}", ""]
        lines.extend(dependency_diagram(identifiers, nodes))
        for identifier, node in nodes.items():
            if identifier not in identifiers:
                continue
            lines += [
                f"### {identifier}",
                "",
                f"**{node['status']}** · {node['role']} · {node['scope']}",
                "",
                node["statement"],
                "",
                f"- **Required** · {links(node['all_of'])}",
                f"- **Alternatives** · {links(node['any_of'])}",
                f"- **Evidence** · {', '.join(map(source_link, node['evidence'])) or 'Pending'}",
                "",
                node["composition"],
                "",
            ]
    return "\n".join(lines)


def task_state(task, nodes, ready):
    target = nodes[task["node"]]
    if target["status"] == "CHECKED":
        return "Checked"
    if proved(target):
        return "Established"
    if task["claim"] is not None:
        return "Claimed"
    return "Ready" if task["id"] in ready else "Blocked"


def render_tasks(tasks, nodes):
    ready = {identifier for identifier, _ in ready_tasks(tasks, nodes)}
    ordered = sorted(tasks.values(), key=lambda task: (task["priority"], task["id"]))
    lines = [
        "<!-- Generated by render.py from dag.json. -->",
        "# Research task cards",
        "",
        "[Overview](README.md) · [Full graph](GRAPH.md) · [Verification](../VERIFICATION.md)",
        "",
        "A card is ready when its target is open, it has no claimant, and its listed prerequisites "
        "are established. Synthesis also requires the target node’s mathematical dependencies.",
        "",
        "| Priority | Task | Status | Target |",
        "| --- | --- | --- | --- |",
    ]
    for task in ordered:
        lines.append(f"| {task['priority']} | {link(task['id'])} | {task_state(task, nodes, ready)} "
                     f"| {link(task['node'], 'GRAPH.md')} |")
    lines.append("")
    priorities = dict.fromkeys(task["priority"] for task in ordered)
    for priority in priorities:
        lines += [f"## {priority}", ""]
        for task in ordered:
            if task["priority"] != priority:
                continue
            claim = task["claim"]
            claimant = f"{claim['owner']} · `{claim['branch']}`" if claim else "Unclaimed"
            if claim and "claimed_at" in claim:
                claimant += f" · {claim['claimed_at']}"
            lines += [
                f"### {task['id']}",
                "",
                f"**{task['title']}**",
                "",
                f"{task['priority']} · {task['mode']} · {task_state(task, nodes, ready)} · {claimant}",
                "",
                f"- **Target** · {link(task['node'], 'GRAPH.md')}",
                f"- **Prerequisites** · {links(task['needs'], 'GRAPH.md')}",
                f"- **Related results** · {links(task['uses'], 'GRAPH.md')}",
                "",
            ]
            for field in ("inputs", "deliverable", "acceptance", "fallback"):
                lines += [f"**{field.capitalize()}**", "", task[field], ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check that both Markdown renders are current")
    args = parser.parse_args()
    graph = json.loads((HERE / "dag.json").read_text(encoding="utf-8"))
    nodes = {node["id"]: node for node in graph["nodes"]}
    tasks = {task["id"]: task for task in graph["tasks"]}
    documents = {"TASKS.md": render_tasks(tasks, nodes), "GRAPH.md": render_graph(graph, nodes)}
    stale = []
    for name, document in documents.items():
        path = HERE / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != document:
                stale.append(name)
        else:
            path.write_text(document, encoding="utf-8")
    if stale:
        parser.exit(1, f"Outdated render: {', '.join(stale)}. Run python3 -B {__file__}.\n")
    print("Verified current task and graph renders." if args.check else "Rendered TASKS.md and GRAPH.md.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
