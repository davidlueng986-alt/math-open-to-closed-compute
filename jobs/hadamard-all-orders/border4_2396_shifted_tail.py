def reflect(row):
    return tuple(row[(ALIGNMENT - i) % N] for i in range(N))


def shifted_negative(t):
    a, b = t[2], reflect(t[3])
    assert tuple(map(abs, a)) == tuple(map(abs, b))
    x = tuple((u + v) // 2 for u, v in zip(a, b, strict=True))
    y = tuple((u - v) // 2 for u, v in zip(a, b, strict=True))
    assert tuple(sum(map(abs, row)) for row in (x, y)) == (85, 84)
    y = tuple(y[(i - SHIFT) % N] for i in range(N))
    assert all(not (u and v) for u, v in zip(x, y, strict=True))
    c = tuple(u + v for u, v in zip(x, y, strict=True))
    d = reflect(tuple(u - v for u, v in zip(x, y, strict=True)))
    result = t[:2] + (c, d)
    assert periodic(result) == [599] + [0] * (N - 1)
    assert tuple(sum(abs(u) != abs(v) for u, v in zip(old, new, strict=True))
                 for old, new in zip(t, result, strict=True)) == (0, 0, 100, 100)
    return result


def compress(row):
    return tuple(sum(row[i::Q]) for i in range(Q))


def verify_lift(patterns, negative, quotient_half, binary_mod16, binary_exact, maximum, energy):
    positive = tuple(map(word, patterns))
    assert tuple(map(sum, positive)) == (0, 1, 0, 0)
    assert all(u*u + v*v == 1 for a, b in zip(positive, negative, strict=True)
               for u, v in zip(a, b, strict=True))
    raw = periodic(positive)
    assert raw[0] == 597 and all((v + 2) % 4 == 0 for v in raw[1:])
    projected = periodic(tuple(map(compress, positive)))
    quotient = [v - (553 if d == 0 else -46) for d, v in enumerate(projected)]
    assert quotient == quotient_half + quotient_half[1:][::-1]
    binary = tuple(tuple(a[i % N] + (-1)**i * b[i % N] for i in range(2 * N))
                   for a, b in zip(positive, negative, strict=True))
    assert all(set(row) <= {-1, 1} for row in binary)
    norms = periodic(binary)
    assert norms[0] == 8 * N
    errors = [v + 4 for v in norms[1:]]
    assert (sum(v % 16 == 0 for v in errors), errors.count(0),
            max(map(abs, errors)), sum(v*v for v in errors)) == (
        binary_mod16, binary_exact, maximum, energy,
    )
    return positive


def main():
    t = nested_negative_words()
    near = tuple(map(word, TWO_FIBER_SOURCE))
    original = verify_lift(ORIGINAL_T_EXACT_C13, t, [0] * 7, 477, 101, 96, 660992)
    broader = verify_lift(ORIGINAL_T_MORE_MOD16, t, [0] * 7, 485, 85, 96, 735232)
    for positive, expected in ((original, (16, 8)), (broader, (6, 6))):
        first_hamming = tuple(sum(u != v for u, v in zip(a, b, strict=True))
                              for a, b in zip(positive[:2], near[:2], strict=True))
        assert first_hamming == expected

    moved = shifted_negative(t)
    exact = verify_lift(SHIFTED_T_EXACT_C13, moved, [0] * 7, 317, 9, 336, 6710784)
    assert compress(tuple(map(abs, exact[2]))) == (9, 10, 10, 8, 10, 11, 11, 9, 11, 10, 11, 11, 9)
    verify_lift(SHIFTED_T_MOD16, moved, [-16, 8, -8, 0, 0, 8, 0], 597, 93, 128, 987136)
    print("Exact C13 verified at 477 and 485 of 597 binary shifts modulo sixteen.")
    print("Shifted exact T verified: exact C13 lift and a separate full modulo-sixteen lift.")


if __name__ == "__main__":
    main()
